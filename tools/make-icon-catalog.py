#!/usr/bin/env python3
"""Schreibt den Icon-Katalog als JavaScript, damit der Launcher ihn ohne fetch laden kann.

Eine Web-App auf dem Fernseher laeuft aus dem Paket (file:// bzw. wgt-package://).
Dort ist fetch auf eine lokale JSON-Datei nicht verlaesslich, ein <script> schon.
Deshalb liegt neben assets/icons.json eine Datei assets/icons-catalog.js mit
demselben Inhalt als window.CleanFrameIcons.

Aufruf: python3 tools/make-icon-catalog.py [--check]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "app", "assets", "icons.json")
OUT = os.path.join(ROOT, "app", "assets", "icons-catalog.js")

HEADER = """/* Generated by tools/make-icon-catalog.py from icons.json. Do not edit. */
window.CleanFrameIcons = """


def build():
    with open(SRC) as f:
        data = json.load(f)
    groups = []
    for g in data.get("groups", []):
        icons = []
        for ic in g.get("icons", []):
            if not ic.get("key") or not ic.get("file"):
                continue
            icons.append({"key": ic["key"], "de": ic.get("de") or ic["key"],
                          "en": ic.get("en") or ic.get("de") or ic["key"], "file": ic["file"]})
        groups.append({"id": g["id"], "label": g.get("label") or {}, "icons": icons})
    return json.dumps({"version": data.get("version", 1), "groups": groups},
                      ensure_ascii=False, indent=1)


def main():
    body = HEADER + build() + ";\n"
    if "--check" in sys.argv:
        current = ""
        if os.path.exists(OUT):
            with open(OUT) as f:
                current = f.read()
        if current != body:
            print("FAIL: icons-catalog.js ist nicht aktuell (python3 tools/make-icon-catalog.py)")
            return 1
        print("ok icons-catalog.js ist aktuell")
        return 0
    with open(OUT, "w") as f:
        f.write(body)
    n = sum(len(g["icons"]) for g in json.loads(build())["groups"])
    print("geschrieben: %s (%d Icons)" % (os.path.relpath(OUT, ROOT), n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
